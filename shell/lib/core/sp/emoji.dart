/// Replaces known `[name]` tokens with emoji; unknown tokens are left alone.
String renderEmoji(String text) {
  if (!text.contains('[')) return text;
  var out = text;
  for (final entry in _emoji.entries) {
    if (out.contains(entry.key)) {
      out = out.replaceAll(entry.key, entry.value);
    }
  }
  return out;
}
